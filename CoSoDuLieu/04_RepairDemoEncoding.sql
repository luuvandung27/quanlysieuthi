-- Repair the exact misencoded demo values produced by the old seed command.
SET XACT_ABORT ON;
SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
BEGIN TRANSACTION;

UPDATE dbo.Products SET Name = N'Nước suối 500 ml'
WHERE Sku = N'DEMO-001' AND CONVERT(varbinary(400), Name) =
    0x4E00C600B000E100BB003A206300200073007500E100BB0018206900200035003000300020006D006C00;
UPDATE dbo.Products SET Name = N'Bánh quy bơ'
WHERE Sku = N'DEMO-002' AND CONVERT(varbinary(400), Name) =
    0x42000201A1006E006800200071007500790020006200C600A100;
UPDATE dbo.Products SET Unit = N'Hộp'
WHERE Sku = N'DEMO-002' AND CONVERT(varbinary(100), Unit) = 0x4800E100BB0022217000;

DECLARE @correctCategory int = (SELECT CategoryId FROM dbo.Categories WHERE Name = N'Demo siêu thị');
IF @correctCategory IS NULL
    UPDATE dbo.Categories SET Name = N'Demo siêu thị'
    WHERE CONVERT(varbinary(200), Name) = 0x440065006D006F002000730069000201AA007500200074006800E100BB003920;
ELSE
    UPDATE p SET CategoryId = @correctCategory
    FROM dbo.Products p INNER JOIN dbo.Categories c ON p.CategoryId = c.CategoryId
    WHERE p.Sku IN (N'DEMO-001', N'DEMO-002')
        AND CONVERT(varbinary(200), c.Name) = 0x440065006D006F002000730069000201AA007500200074006800E100BB003920;

UPDATE dbo.Suppliers SET Name = N'Nhà cung cấp mẫu'
WHERE SupplierCode = N'DEMO-NCC' AND CONVERT(varbinary(400), Name) =
    0x4E0068000201A0002000630075006E00670020006300E100BA00A500700020006D00E100BA00AB007500;
UPDATE dbo.Customers SET FullName = N'Khách hàng mẫu'
WHERE CustomerCode = N'DEMO-KH' AND CONVERT(varbinary(400), FullName) =
    0x4B0068000201A10063006800200068000201A0006E00670020006D00E100BA00AB007500;

COMMIT;
